// 문자열을 정수 시드로 변환 (djb2 해시)
function seedFromString(str) {
  let hash = 5381;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) + hash + str.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}

// 생년월일(month, day)로 별자리 key 찾기
function getZodiacKeyByDate(month, day) {
  for (const key of ZODIAC_ORDER) {
    const info = ZODIAC[key];
    const [sMonth, sDay] = info.start;
    const [eMonth, eDay] = info.end;
    if (sMonth <= eMonth) {
      if ((month === sMonth && day >= sDay) || (month === eMonth && day <= eDay) || (month > sMonth && month < eMonth)) {
        return key;
      }
    } else {
      // 염소자리처럼 연말/연초를 걸치는 경우
      if ((month === sMonth && day >= sDay) || (month === eMonth && day <= eDay)) {
        return key;
      }
    }
  }
  return null;
}

// 오늘 날짜 기준 YYYY-MM-DD 문자열
function getTodayDateString() {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

// 별자리 + 날짜 시드로 오늘의 운세 계산 (같은 날 같은 별자리는 항상 같은 결과)
function getDailyFortune(zodiacKey, dateString) {
  dateString = dateString || getTodayDateString();
  const baseSeed = seedFromString(`${zodiacKey}-${dateString}`);

  const categories = ["love", "money", "health", "work"];
  const result = {};
  categories.forEach((cat, i) => {
    const slice = (baseSeed >> (i * 5)) & 0xff;
    const stars = (slice % 5) + 1;
    const messages = FORTUNE_MESSAGES[cat];
    const msgIndex = (baseSeed + i * 37) % messages.length;
    result[cat] = { stars, message: messages[msgIndex] };
  });

  const colorIndex = (baseSeed >> 20) % LUCKY_COLORS.length;
  const adviceIndex = (baseSeed >> 24) % LUCKY_ADVICE.length;
  const luckyNum = (baseSeed % 9) + 1;

  return {
    ...result,
    luckyNumber: luckyNum,
    luckyColor: LUCKY_COLORS[colorIndex],
    advice: LUCKY_ADVICE[adviceIndex],
  };
}

// 두 별자리 간 궁합 점수 계산 (별자리 12궁 각도를 기반으로 한 결정적 점수, 0~100)
function getCompatScore(key1, key2) {
  if (key1 === key2) return 95;
  const i1 = ZODIAC_ORDER.indexOf(key1);
  const i2 = ZODIAC_ORDER.indexOf(key2);
  if (i1 === -1 || i2 === -1) return 50;

  let dist = Math.abs(i1 - i2);
  if (dist > 6) dist = 12 - dist;

  const baseByDist = { 0: 95, 1: 58, 2: 80, 3: 52, 4: 92, 5: 46, 6: 68 };
  const base = baseByDist[dist];
  const variation = ((i1 * 7 + i2 * 13) % 7) - 3; // -3 ~ 3
  const score = base + variation;
  return Math.max(30, Math.min(99, score));
}

